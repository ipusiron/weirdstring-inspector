'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.join(__dirname, '..');
const inputs = [
  ['emoji-sequences.txt', 'emoji/emoji-sequences.txt', '1823dce71f3dd9cb0ad1976797baee4ffbdc1909756f43af8ce4c57f732843a4'],
  ['StandardizedVariants.txt', 'ucd/StandardizedVariants.txt', 'c7ae634a7e2bb0932258548a1e81df984fbb38e30cecf4269391d6a4f94581ac'],
  ['emoji-variation-sequences.txt', 'ucd/emoji/emoji-variation-sequences.txt', 'ff1707564aa1f1b2fcf4ec92d609d4cb26940bc0d4dcf07f5328ad6879e84da3']
];
const sources = inputs.map(([name, url, sha256]) => {
  const bytes = fs.readFileSync(path.join(__dirname, 'unicode', name));
  if (crypto.createHash('sha256').update(bytes).digest('hex') !== sha256) throw new Error('Source hash mismatch: ' + name);
  return { name, url: 'https://www.unicode.org/Public/18.0.0/' + url, sha256, text: bytes.toString('utf8') };
});
const entries = source => source.text.split(/\r?\n/).map(line => line.split('#')[0].trim()).filter(Boolean)
  .map(line => line.split(';').map(part => part.trim()));
const rgiFlags = entries(sources[0]).filter(row => row[1] === 'RGI_Emoji_Tag_Sequence').map(row => row[0]);
const variants = [...new Set(sources.slice(1).flatMap(source => entries(source).map(row => row[0])))].sort();
const japanesePairs = [
  [0x4e00, 0x30fc], [0x3078, 0x30d8], [0x4e8c, 0x30cb], [0x516b, 0x30cf],
  [0x529b, 0x30ab], [0x535c, 0x30c8], [0x53e3, 0x30ed], [0x5915, 0x30bf],
  [0x5de5, 0x30a8], [0x53b6, 0x30e0], [0x5315, 0x30d2], [0x4ebb, 0x30a4],
  [0x5f50, 0x30e8], [0x793b, 0x30cd], [0x6729, 0x30db], [0x4e44, 0x30e1]
];
const confusables = fs.readFileSync(path.join(__dirname, 'unicode', 'confusables.txt'), 'utf8');
const mapping = new Set(confusables.split(/\r?\n/).map(line => line.split('#')[0].split(';').slice(0, 2)
  .map(field => field.trim()).join(';')));
const hex = cp => cp.toString(16).toUpperCase().padStart(4, '0');
for (const [a, b] of japanesePairs) {
  if (!mapping.has(hex(a) + ';' + hex(b)) && !mapping.has(hex(b) + ';' + hex(a))) throw new Error('Missing Japanese pair');
}
const data = { unicodeVersion: '18.0.0', rgiFlags, variants, japanesePairs };
const manifest = {
  unicodeVersion: '18.0.0', retrieved: '2026-09-22',
  sources: sources.map(({ name, url, sha256 }) => ({ name, url, sha256 })),
  counts: { rgiFlags: rgiFlags.length, variants: variants.length, japanesePairs: japanesePairs.length }
};
const generated = '// Generated by tools/build-context-data.js. Do not edit.\n(function (root) {\n  \'use strict\';\n' +
  '  const data = ' + JSON.stringify(data, null, 2).split('\n').join('\n  ') + ';\n' +
  '  if (typeof module === \'object\' && module.exports) {\n    module.exports = data;\n' +
  '  } else {\n    root.WeirdStringContextData = data;\n  }\n})(globalThis);\n';
let mismatch = false;
for (const [name, text] of [
  ['weirdstring-context-data.js', generated], ['tools/unicode/context-manifest.json', JSON.stringify(manifest, null, 2) + '\n']
]) {
  const file = path.join(root, name);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== text) {
      process.stderr.write('Mismatch: ' + name + '\n');
      mismatch = true;
    }
  } else fs.writeFileSync(file, text);
}
if (mismatch) process.exitCode = 1;
else process.stdout.write(JSON.stringify(manifest.counts) + '\n');
